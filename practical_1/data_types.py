# integer type
integer_type = int(17)
print(integer_type)
print(type(integer_type))

#float type
float_type = 5.6
print(float_type)
print(type(float_type))

# string type
str_type = "Vasileos"
print(str_type)
print(type(str_type))

# boolean type
boolean_type = True
print(boolean_type)
print(type(boolean_type))

# nonetype type
nonetype = None 
print(nonetype)
print(type(nonetype))

# list type
list_type = ["Irak", "Iran", "Pakistan", "Uzbekistan", "Turkmenistan", "Spain"]
print(list_type)
print(type(list_type))

# dictionary type
dict_type = {"Ali": "Irak", "Sacha": "France", "Jorge": "Spain", "Vasileos": "Anatolia"}
print(dict_type)
print(type(dict_type))

# tuple type
tuple_type = ("Jews", "Muslims", "Christians", "Buddhist", "Yaoists")
print(tuple_type)
print(type(tuple_type))

# set type
set_type = {1, "blablablablebleblebleblobloblo", 4, 9, 4.5, "kebab"}
print(set_type)
print(type(set_type))

# range type
range_type = range(1, 99)
print(range_type)
print(type(range_type))
